SET client_encoding = 'UTF8';

CREATE EXTENSION IF NOT EXISTS pgcrypto;

DROP TABLE IF EXISTS
    auditoria, detalle_presupuesto, presupuesto, consumo_material,
    evidencia, respuesta_checklist, hoja_servicio, asignacion,
    orden_trabajo, item_checklist, checklist, material, equipo,
    obra, cliente, usuario
CASCADE;

CREATE TABLE usuario (
    id_usuario        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut               VARCHAR(20)  NOT NULL UNIQUE,
    nombre            VARCHAR(120) NOT NULL,
    correo            VARCHAR(120) UNIQUE,
    password_hash     TEXT         NOT NULL,
    rol               VARCHAR(20)  NOT NULL
                      CHECK (rol IN ('tecnico', 'administrador', 'erp')),
    zona              VARCHAR(80),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    intentos_fallidos INTEGER      NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
    bloqueado_hasta   TIMESTAMPTZ
);

CREATE TABLE cliente (
    id_cliente      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut             VARCHAR(20)  NOT NULL UNIQUE,
    razon_social    VARCHAR(160) NOT NULL,
    nombre_contacto VARCHAR(120),
    telefono        VARCHAR(30),
    correo          VARCHAR(120),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE obra (
    id_obra     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente  BIGINT       NOT NULL REFERENCES cliente (id_cliente),
    nombre      VARCHAR(160) NOT NULL,
    direccion   VARCHAR(200),
    descripcion TEXT,
    estado      VARCHAR(30)  NOT NULL DEFAULT 'ACTIVA'
);

CREATE TABLE equipo (
    id_equipo         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente        BIGINT       NOT NULL REFERENCES cliente (id_cliente),
    codigo_qr         VARCHAR(60)  UNIQUE,
    numero_ficha      VARCHAR(30),
    tipo_equipo       VARCHAR(80),
    nombre            VARCHAR(160) NOT NULL,
    marca             VARCHAR(80),
    modelo            VARCHAR(80),
    numero_serie      VARCHAR(80),
    ubicacion         VARCHAR(160),
    horometro_actual  NUMERIC(10,1),
    ultima_mantencion DATE,
    estado_general    VARCHAR(40),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE orden_trabajo (
    id_orden         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente       BIGINT       NOT NULL REFERENCES cliente (id_cliente),
    id_obra          BIGINT       REFERENCES obra (id_obra),
    id_equipo        BIGINT       REFERENCES equipo (id_equipo),
    codigo_orden_erp VARCHAR(40),
    titulo           VARCHAR(200) NOT NULL,
    descripcion      TEXT,
    tipo_servicio    VARCHAR(40)  NOT NULL,
    prioridad        VARCHAR(20)  NOT NULL DEFAULT 'NORMAL'
                     CHECK (prioridad IN ('BAJA', 'NORMAL', 'ALTA')),
    fecha_programada TIMESTAMPTZ,
    estado           VARCHAR(30)  NOT NULL DEFAULT 'PENDIENTE'
                     CHECK (estado IN ('PENDIENTE', 'EN_EJECUCION', 'FINALIZADA', 'CANCELADA'))
);

CREATE TABLE asignacion (
    id_asignacion    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden         BIGINT      NOT NULL REFERENCES orden_trabajo (id_orden),
    id_tecnico       BIGINT      NOT NULL REFERENCES usuario (id_usuario),
    fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    activa           BOOLEAN     NOT NULL DEFAULT TRUE,
    UNIQUE (id_orden, id_tecnico)
);

CREATE TABLE checklist (
    id_checklist  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(160) NOT NULL,
    tipo_servicio VARCHAR(40)  NOT NULL,
    version       INTEGER      NOT NULL DEFAULT 1 CHECK (version > 0),
    activo        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE item_checklist (
    id_item      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_checklist BIGINT       NOT NULL REFERENCES checklist (id_checklist),
    pregunta     VARCHAR(255) NOT NULL,
    obligatorio  BOOLEAN      NOT NULL DEFAULT TRUE,
    orden        INTEGER      NOT NULL CHECK (orden > 0),
    UNIQUE (id_checklist, orden)
);

CREATE TABLE hoja_servicio (
    id_hoja                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_asignacion          BIGINT      NOT NULL REFERENCES asignacion (id_asignacion),
    id_checklist           BIGINT      NOT NULL REFERENCES checklist (id_checklist),
    fecha_inicio           TIMESTAMPTZ,
    fecha_fin              TIMESTAMPTZ,
    horometro_servicio     NUMERIC(10,1) CHECK (horometro_servicio >= 0),
    actividades            TEXT,
    observaciones_tecnicas TEXT,
    estado_servicio        VARCHAR(20) NOT NULL DEFAULT 'EN_EJECUCION'
                           CHECK (estado_servicio IN ('EN_EJECUCION', 'FINALIZADO')),
    resultado              VARCHAR(30)
                           CHECK (resultado IN ('OPERATIVO', 'REQUIERE_SEGUIMIENTO', 'FUERA_DE_SERVICIO')),
    estado_envio_erp       VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                           CHECK (estado_envio_erp IN ('PENDIENTE', 'ENVIADO', 'SINCRONIZADO', 'ERROR')),
    codigo_hoja_erp        VARCHAR(40),
    fecha_envio_erp        TIMESTAMPTZ,
    id_dispositivo         VARCHAR(60),
    version                INTEGER     NOT NULL DEFAULT 1,
    CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE respuesta_checklist (
    id_hoja        UUID   NOT NULL REFERENCES hoja_servicio (id_hoja) ON DELETE CASCADE,
    id_item        BIGINT NOT NULL REFERENCES item_checklist (id_item),
    pregunta_texto VARCHAR(255),
    resultado      VARCHAR(30),
    observacion    TEXT,
    PRIMARY KEY (id_hoja, id_item)
);

CREATE TABLE material (
    id_material         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_material_erp VARCHAR(40) UNIQUE,
    nombre              VARCHAR(160) NOT NULL,
    unidad_medida       VARCHAR(20)  NOT NULL,
    stock_referencial   NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (stock_referencial >= 0),
    stock_minimo        NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    activo              BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE consumo_material (
    id_consumo            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_hoja               UUID          NOT NULL REFERENCES hoja_servicio (id_hoja) ON DELETE CASCADE,
    id_material           BIGINT        NOT NULL REFERENCES material (id_material),
    cantidad              NUMERIC(12,2) NOT NULL CHECK (cantidad > 0),
    fecha_registro        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    estado                VARCHAR(20)   NOT NULL DEFAULT 'REGISTRADO'
                          CHECK (estado IN ('REGISTRADO', 'ENVIADO')),
    codigo_movimiento_erp VARCHAR(40)
);

CREATE TABLE presupuesto (
    id_presupuesto   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_cliente       BIGINT      NOT NULL REFERENCES cliente (id_cliente),
    id_orden         BIGINT      REFERENCES orden_trabajo (id_orden),
    id_tecnico       BIGINT      NOT NULL REFERENCES usuario (id_usuario),
    id_aprobador     BIGINT      REFERENCES usuario (id_usuario),
    lugar_trabajo    VARCHAR(200),
    descripcion      TEXT,
    fecha_creacion   TIMESTAMPTZ NOT NULL DEFAULT now(),
    estado           VARCHAR(20) NOT NULL DEFAULT 'ENVIADO'
                     CHECK (estado IN ('ENVIADO', 'EN_COSTEO', 'APROBADO', 'RECHAZADO')),
    monto_estimado   NUMERIC(14,2) CHECK (monto_estimado >= 0),
    monto_aprobado   NUMERIC(14,2) CHECK (monto_aprobado >= 0),
    observacion_oficina TEXT
);

CREATE TABLE detalle_presupuesto (
    id_detalle      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_presupuesto  UUID          NOT NULL REFERENCES presupuesto (id_presupuesto) ON DELETE CASCADE,
    id_material     BIGINT        REFERENCES material (id_material),
    descripcion     VARCHAR(255)  NOT NULL,
    cantidad        NUMERIC(12,2) NOT NULL CHECK (cantidad > 0),
    unidad_medida   VARCHAR(20),
    precio_unitario NUMERIC(14,2) CHECK (precio_unitario >= 0)
);

CREATE TABLE evidencia (
    id_evidencia   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_hoja        UUID         NOT NULL REFERENCES hoja_servicio (id_hoja) ON DELETE CASCADE,
    id_usuario     BIGINT       NOT NULL REFERENCES usuario (id_usuario),
    tipo           VARCHAR(10)  NOT NULL CHECK (tipo IN ('foto', 'firma')),
    clave_archivo  TEXT         NOT NULL UNIQUE,
    formato        VARCHAR(20)  NOT NULL CHECK (formato IN ('jpg', 'png', 'webp')),
    fecha_captura  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    latitud        NUMERIC(9,6) CHECK (latitud BETWEEN -90 AND 90),
    longitud       NUMERIC(9,6) CHECK (longitud BETWEEN -180 AND 180),
    nombre_firmante VARCHAR(120),
    rut_firmante   VARCHAR(20),
    sha256         VARCHAR(64),
    estado_carga   VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE'
                   CHECK (estado_carga IN ('PENDIENTE', 'GUARDADO', 'ERROR'))
);

CREATE TABLE auditoria (
    id_auditoria         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario           BIGINT      REFERENCES usuario (id_usuario),
    tabla_afectada       VARCHAR(60) NOT NULL,
    id_registro_afectado VARCHAR(60),
    accion               VARCHAR(30) NOT NULL,
    fecha                TIMESTAMPTZ NOT NULL DEFAULT now(),
    valor_anterior       JSONB,
    valor_nuevo          JSONB
);

CREATE INDEX idx_asignacion_tecnico ON asignacion (id_tecnico, activa);
CREATE INDEX idx_hoja_asignacion ON hoja_servicio (id_asignacion);
CREATE INDEX idx_hoja_estado_envio ON hoja_servicio (estado_envio_erp);
CREATE INDEX idx_respuesta_hoja ON respuesta_checklist (id_hoja);
CREATE INDEX idx_consumo_hoja ON consumo_material (id_hoja);
CREATE INDEX idx_evidencia_hoja ON evidencia (id_hoja);
CREATE INDEX idx_presupuesto_tecnico_estado ON presupuesto (id_tecnico, estado);
CREATE INDEX idx_material_nombre ON material (nombre);
